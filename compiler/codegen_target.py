"""
Illustrative Target Code Generator for Malayalam Educational Compiler.
Emits clean, well-commented Assembly (RISC/MIPS style) with register allocation,
.data segment for variables & string constants, and .text segment for instructions.
"""

from typing import List, Dict, Set, Tuple
from .codegen_tac import TACInstruction
from .optimizer import is_number, is_string_literal, parse_string


class TargetCodeGenerator:
    def __init__(self):
        self.assembly_lines: List[str] = []
        self.data_symbols: Dict[str, str] = {}  # symbol -> init_value
        self.string_literals: Dict[str, str] = {}  # str_label -> string_value
        self.str_counter = 0

    def generate(self, instructions: List[TACInstruction]) -> str:
        self.assembly_lines.clear()
        self.data_symbols.clear()
        self.string_literals.clear()
        self.str_counter = 0

        # Scan instructions to identify all variables and string constants
        self._collect_symbols(instructions)

        code_lines: List[str] = []

        # Generate assembly for each TAC instruction
        for inst in instructions:
            code_lines.extend(self._translate_instruction(inst))

        # Build full assembly listing
        output = [
            "; =================================================================",
            "; Target Assembly Code (RISC/MIPS-style Architecture)",
            "; Generated by Malayalam Educational Compiler Pipeline",
            "; =================================================================",
            "",
            ".data",
            "    ; Global Variables and Constants",
        ]

        if not self.data_symbols and not self.string_literals:
            output.append("    ; (No global variables)")
        else:
            for str_lbl, str_val in self.string_literals.items():
                escaped = repr(str_val)
                output.append(f"    {str_lbl:12}: .asciiz {escaped}")
            for var_name, var_type in self.data_symbols.items():
                output.append(f"    {var_name:12}: .word 0")

        output.extend([
            "",
            ".text",
            ".global main",
            "main:",
            "    ; Program Entry Point",
        ])

        output.extend(code_lines)

        output.extend([
            "",
            "    ; Exit Program",
            "    HALT",
        ])

        return "\n".join(output)

    def _collect_symbols(self, instructions: List[TACInstruction]):
        for inst in instructions:
            for operand in (inst.arg1, inst.arg2, inst.result):
                if operand:
                    if is_string_literal(operand):
                        val = parse_string(operand)
                        if val not in self.string_literals.values():
                            lbl = f"str_{self.str_counter}"
                            self.str_counter += 1
                            self.string_literals[lbl] = val
                    elif not is_number(operand) and operand not in ("true", "false") and not operand.startswith("L"):
                        # It's a variable or temporary
                        if operand not in self.data_symbols:
                            self.data_symbols[operand] = ".word"

    def _get_string_label(self, val: str) -> str:
        parsed = parse_string(val)
        for lbl, s in self.string_literals.items():
            if s == parsed:
                return lbl
        lbl = f"str_{self.str_counter}"
        self.str_counter += 1
        self.string_literals[lbl] = parsed
        return lbl

    def _load_operand(self, reg: str, operand: str) -> List[str]:
        if is_number(operand):
            return [f"    LOAD_IMM  {reg}, {operand}"]
        elif is_string_literal(operand):
            lbl = self._get_string_label(operand)
            return [f"    LOAD_ADDR {reg}, {lbl}"]
        elif operand == "true":
            return [f"    LOAD_IMM  {reg}, 1"]
        elif operand == "false":
            return [f"    LOAD_IMM  {reg}, 0"]
        else:
            return [f"    LOAD      {reg}, [{operand}]"]

    def _translate_instruction(self, inst: TACInstruction) -> List[str]:
        lines: List[str] = []
        op = inst.op

        if inst.comment:
            lines.append(f"    ; {inst.comment}")

        if op == "LABEL":
            lines.append(f"{inst.result}:")
            return lines

        if op == "GOTO":
            lines.append(f"    JMP       {inst.result}")
            return lines

        if op == "IF_FALSE":
            # Test arg1, if zero/false jump to label
            lines.extend(self._load_operand("R0", inst.arg1))
            lines.append(f"    CMP_ZERO  R0")
            lines.append(f"    JMP_EQ    {inst.result}       ; Jump if condition is false/zero")
            return lines

        if op == "IF_TRUE":
            lines.extend(self._load_operand("R0", inst.arg1))
            lines.append(f"    CMP_ZERO  R0")
            lines.append(f"    JMP_NE    {inst.result}       ; Jump if condition is true/nonzero")
            return lines

        if op == "PRINT":
            lines.extend(self._load_operand("R0", inst.arg1))
            lines.append(f"    OUT_VAL   R0              ; Syscall: Display output (കാണിക്കുക)")
            return lines

        if op == "READ":
            if inst.arg2:
                lines.extend(self._load_operand("R0", repr(inst.arg2)))
                lines.append(f"    OUT_VAL   R0              ; Show prompt before input")
            lines.append(f"    IN_VAL    R0              ; Syscall: Read user input (വായിക്കുക)")
            lines.append(f"    STORE     R0, [{inst.result}]")
            return lines

        if op == "=":
            lines.extend(self._load_operand("R0", inst.arg1))
            lines.append(f"    STORE     R0, [{inst.result}]")
            return lines

        if op in ("neg", "not"):
            lines.extend(self._load_operand("R0", inst.arg1))
            if op == "neg":
                lines.append(f"    NEG       R0, R0")
            else:
                lines.append(f"    NOT       R0, R0")
            lines.append(f"    STORE     R0, [{inst.result}]")
            return lines

        # Binary operations
        lines.extend(self._load_operand("R0", inst.arg1))
        lines.extend(self._load_operand("R1", inst.arg2))

        op_map = {
            "+": "ADD",
            "-": "SUB",
            "*": "MUL",
            "/": "DIV",
            "%": "MOD",
            "==": "CMP_EQ",
            "!=": "CMP_NE",
            "<": "CMP_LT",
            ">": "CMP_GT",
            "<=": "CMP_LE",
            ">=": "CMP_GE",
            "and": "AND",
            "or": "OR",
        }

        asm_op = op_map.get(op, "ADD")
        lines.append(f"    {asm_op:9} R2, R0, R1")
        lines.append(f"    STORE     R2, [{inst.result}]")

        return lines
